/* ============================================================
   חיפוש מקומי
   ------------------------------------------------------------
   שני דברים שהניקוד התמים לא תפס, ולכן הם כתובים כאן במפורש:

   1. תחיליות. "מה זה החלון הצף" לא התאים ל"חלון צף", כי ה"א
      הידיעה הדביקה אות. לכן שני הצדדים עוברים אותו קיצוץ.
      גם כשהוא חותך יותר מדי ("מחיר" → "חיר") זה לא מזיק, כי
      הטריגר עובר את אותו הטיפול.

   2. כיסוי. "להעלות מחיר או להוריד זמן" הכיל את המילה "מחיר"
      ולכן קיבל תשובה על עמוד הכסף — במקום ללכת לקלוד ולענות
      על השאלה העסקית שנשאלה. מילה אחת מתוך חמש אינה התאמה.
      לכן נמדד גם כמה מהשאלה ההתאמה מסבירה.
   ============================================================ */

const PREFIX = /^[הובלכמש]/;

const clean = s => String(s || '')
  .replace(/[?!.,;:"'״׳()]/g, ' ')
  .replace(/\s+/g, ' ')
  .trim();

/* מקצצים תחיליות עד הסוף ולא אחת: "הוואטסאפ" נושא שתיים, ואם
   נעצור אחרי הראשונה הוא לא יפגוש את "וואטסאפ" שנושא אחת. */
const stem = w => { while (w.length > 2 && PREFIX.test(w)) w = w.slice(1); return w; };
const wordsOf = s => clean(s).split(' ').filter(Boolean).map(stem);

/* מילות שאלה ומילות קישור — לא נספרות בכיסוי, כי הן בכל שאלה */
const STOP = new Set(wordsOf(
  'איך מה איפה למה מתי מי האם אפשר צריך כדי ' +
  'זה זאת את של על עם אני לי יש אין ' +
  'עושים עושה לעשות בבקשה תגיד גם רק או אבל כמו'
));

export function search(query, limit = 3) {
  const qw = wordsOf(query);
  const q = ' ' + qw.join(' ') + ' ';
  if (q.length < 4) return [];
  const content = qw.filter(w => w.length > 1 && !STOP.has(w));

  return ENTRIES
    .map(e => {
      let score = 0;
      const hitWords = new Set();
      const mark = w => { if (content.includes(w)) hitWords.add(w); };

      for (const trig of e.q) {
        const tw = wordsOf(trig);
        const t = ' ' + tw.join(' ') + ' ';
        if (q.includes(t)) {                                 // ביטוי שלם, על גבולות מילים
          score += 10 + t.length / 4;
          tw.forEach(mark);
        } else {
          const rel = tw.filter(w => w.length > 1);
          const hit = rel.filter(w => qw.includes(w));
          hit.forEach(mark);
          if (hit.length && hit.length === rel.length) score += 6;   // כל מילות הטריגר
          else score += hit.length * 1.5;
        }
      }

      return { entry: e, score, coverage: content.length ? hitWords.size / content.length : 0 };
    })
    .filter(x => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);
}

/** תשובה ודאית, או null אם אין התאמה מספיק חזקה */
export function answer(query) {
  const hits = search(query, 2);
  if (!hits.length || hits[0].score < 8) return null;
  // ההתאמה מסבירה פחות מחצי מהשאלה — כנראה מילה משותפת במקרה
  if (hits[0].coverage < 0.5) return null;
  // שתי התאמות קרובות = השאלה עמומה, עדיף לתת לקלוד לפרש
  if (hits[1] && hits[1].score > hits[0].score * 0.85) return null;
  return hits[0].entry;
}

/** גרסה דחוסה לפרומפט: מה קיים במערכת, בלי הטקסט המלא */
export function forPrompt() {
  return ENTRIES.map(e => `- ${e.q[0]}: ${e.a.replace(/\s+/g, ' ')}`).join('\n');
}
